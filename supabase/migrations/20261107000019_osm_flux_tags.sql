-- Relançable sans erreur. Demande les migrations 20261102000016 et 20261102000017.
--
-- `osm_flux` : ce que la synchronisation OpenStreetMap extrait (tag → donnée → fichier). Remplace la liste écrite
--   dans le code de l'API (scripts/osm/categories.ts), qui ne sert plus que de secours. Préremplie avec ses 33 flux.
-- `osm_tags` : inventaire des tags présents en Algérie (≥ 30 objets), mis à jour à chaque passage du robot.
--   Un tag apparu depuis le passage précédent arrive « nouveau » ; l'administration le classe ensuite
--   « à étudier » ou « écarté ». « Pris » n'est pas stocké : c'est un tag qu'un flux extrait déjà.
-- Lecture : permission synchro.gerer. Écriture : seulement l'API (clé secrète), qui vérifie les droits.
-- =====================================================================

create table if not exists public.osm_flux (
  code text primary key check (code ~ '^[a-z0-9-]{2,40}$'),
  dataset_slug text not null check (dataset_slug ~ '^[a-z0-9-]{1,80}$'),
  fichier text not null check (fichier ~ '^[A-Za-z0-9_-]{1,80}$'),
  filtres text[] not null check (cardinality(filtres) between 1 and 10),
  exige jsonb not null default '{}'::jsonb,
  rayon_m integer check (rayon_m between 10 and 20000),
  actif boolean not null default true,
  ordre integer not null default 1000,
  dernier_compte integer,
  dernier_compte_le timestamptz,
  cree_le timestamptz not null default now(),
  modifie_le timestamptz not null default now(),
  unique (dataset_slug, fichier)
);

comment on table public.osm_flux is
  'Synchronisation OpenStreetMap : un flux = des tags (osmium tags-filter, « nwr/cle=v1,v2 ») rangés dans un fichier d''une donnée. Le premier flux (ordre) d''une donnée OpenStreetMap en est le fichier principal.';

create table if not exists public.osm_tags (
  cle text not null,
  valeur text not null,
  nb integer not null,
  nb_precedent integer,
  etat text not null default 'nouveau' check (etat in ('nouveau', 'a_etudier', 'ecarte')),
  premier_vu date not null default current_date,
  dernier_vu date not null default current_date,
  primary key (cle, valeur)
);

comment on table public.osm_tags is
  'Inventaire des tags OpenStreetMap de l''Algérie (au moins 30 objets), tenu à jour par la synchronisation.';

alter table public.osm_flux enable row level security;
alter table public.osm_tags enable row level security;

drop policy if exists "Flux OSM : lecture par les gestionnaires" on public.osm_flux;
create policy "Flux OSM : lecture par les gestionnaires" on public.osm_flux
  for select to authenticated using (public.a_permission('synchro.gerer'));

drop policy if exists "Tags OSM : lecture par les gestionnaires" on public.osm_tags;
create policy "Tags OSM : lecture par les gestionnaires" on public.osm_tags
  for select to authenticated using (public.a_permission('synchro.gerer'));

grant select on public.osm_flux, public.osm_tags to authenticated;
grant all on public.osm_flux, public.osm_tags to service_role;

-- Inventaire déposé par le robot : nouveaux tags « nouveau », comptages mis à jour, état choisi par l'admin gardé.
-- Renvoie les tags apparus. Réservée à l'API (service_role).
create or replace function public.enregistrer_inventaire_osm(p_tags jsonb, p_flux jsonb default '[]'::jsonb)
returns table (cle text, valeur text, nb integer)
language plpgsql
security definer
set search_path = ''
as $$
#variable_conflict use_column
declare
  premier boolean := not exists (select 1 from public.osm_tags);
begin
  create temporary table if not exists _inventaire_osm (cle text, valeur text, nb integer, existait boolean) on commit drop;
  truncate _inventaire_osm;
  insert into _inventaire_osm (cle, valeur, nb, existait)
  select t.cle, t.valeur, max(t.nb), exists (select 1 from public.osm_tags o where o.cle = t.cle and o.valeur = t.valeur)
  from jsonb_to_recordset(p_tags) as t (cle text, valeur text, nb integer)
  where t.cle is not null and t.valeur is not null and t.nb is not null
  group by t.cle, t.valeur;

  insert into public.osm_tags as o (cle, valeur, nb, etat)
  select i.cle, i.valeur, i.nb, case when premier then 'a_etudier' else 'nouveau' end
  from _inventaire_osm i
  on conflict (cle, valeur) do update
    set nb_precedent = o.nb, nb = excluded.nb, dernier_vu = current_date;

  update public.osm_flux f
     set dernier_compte = c.nb, dernier_compte_le = now()
    from jsonb_to_recordset(p_flux) as c (code text, nb integer)
   where f.code = c.code;

  return query select i.cle, i.valeur, i.nb from _inventaire_osm i where not i.existait and not premier order by i.nb desc;
end;
$$;

revoke all on function public.enregistrer_inventaire_osm(jsonb, jsonb) from public, anon, authenticated;
grant execute on function public.enregistrer_inventaire_osm(jsonb, jsonb) to service_role;

